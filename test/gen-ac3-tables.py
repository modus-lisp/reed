def lisp(name, vals, dims=None):
    if dims is None:
        return (f"(defparameter +ac3-{name}+\n  (make-array {len(vals)} :element-type 'fixnum\n"
                f"    :initial-contents '({' '.join(map(str,vals))})))\n"
                f"(declaim (type (simple-array fixnum ({len(vals)})) +ac3-{name}+))\n")
    r, c = dims
    rows = [vals[i*c:(i+1)*c] for i in range(r)]
    body = ' '.join('(' + ' '.join(map(str,row)) + ')' for row in rows)
    return (f"(defparameter +ac3-{name}+\n  (make-array '({r} {c}) :element-type 'fixnum\n"
            f"    :initial-contents '({body})))\n"
            f"(declaim (type (simple-array fixnum ({r} {c})) +ac3-{name}+))\n")

