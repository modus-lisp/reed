import re, sys
def carray(text, name):
    """The initialiser braces of a C array declaration, as a flat list of ints.

    SIGNEDNESS COMES FROM THE DECLARED C TYPE and has to: ff_ac3_floor_tab is int16_t and its last
    entry is written 0xf800, which is -2048.  Read unsigned it is 63488, the masking floor goes to
    the moon, every bit allocation pointer comes out zero, and the decoder reads no mantissas at
    all -- a failure that looks nothing like a table transcribed wrong."""
    i = text.index(name)
    decl = text[max(0, i-40):i]
    signed = ('int8_t' in decl or 'int16_t' in decl or 'int32_t' in decl) and 'uint' not in decl
    width = 8 if 'int8_t' in decl else (16 if 'int16_t' in decl else 32)
    j = text.index('{', i)
    depth = 0
    for k in range(j, len(text)):
        if text[k] == '{': depth += 1
        elif text[k] == '}':
            depth -= 1
            if depth == 0: end = k; break
    body = text[j:end+1]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    vals = [int(t, 0) for t in re.findall(r'-?\b(?:0[xX][0-9a-fA-F]+|\d+)\b', body)]
    if signed:
        lim = 1 << (width - 1)
        vals = [v - 2 * lim if v >= lim else v for v in vals]
    return vals

